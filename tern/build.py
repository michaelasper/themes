#!/usr/bin/env python3
"""Generate Tern's dr-pepper.css from themes/dr-pepper.json and the Pi theme's omp tokens."""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
base = json.loads((root / "themes" / "dr-pepper.json").read_text())
pi_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path.home() / "source/theme/pi/themes/dr-pepper.json"
pi = json.loads(pi_path.read_text())
pi_vars = pi["vars"]

def resolve(v):
    seen = 0
    while isinstance(v, str) and not v.startswith("#") and v in pi_vars and seen < 8:
        v, seen = pi_vars[v], seen + 1
    return v

c, ansi = base["colors"], base["ansi"]
lines = ['/* Generated by tern/build.py from themes/dr-pepper.json. Do not edit. */',
         '@import "dark";', '', ':root {', '\tcolor-scheme: dark;']

def var(name, value):
    lines.append(f"\t--{name}: {value};")

var("tv-bg", base["background"]); var("tv-fg", base["foreground"])
var("tv-cur", base["cursor"]); var("tv-cur-ink", base["background"])
var("tv-sel-a", base["selection"]); var("tv-sel-b", base["selection"])
for i, col in enumerate(ansi):
    var(f"ansi{i}", col)
var("page", c["chrome"]); var("card", c["surface"]); var("raise", c["selected"])
var("code-bg", c["chrome"]); var("tbl-head", c["chrome"]); var("pop-bg", c["selected"])
var("ink", base["foreground"])
for n, col in zip((1, 2, 3, 4), (base["foreground"], ansi[8], c["muted"], "#6a5a62")):
    var(f"t{n}", col)
var("accent", c["accent"]); var("accent-ink", c["accent"]); var("accent-fill", base["cursor"])
var("a1", c["accent"]); var("a2", base["cursor"]); var("grad-ink", c["chrome"])
var("ok", ansi[2]); var("bad", ansi[1]); var("warn", ansi[3]); var("live", ansi[5])
var("ok-fill", "#5f7a4a"); var("bad-fill", "#a84454"); var("live-fill", "#7f5a7a")
lines.append("")
for token, value in pi["colors"].items():
    r = resolve(value)
    if isinstance(r, str) and r.startswith("#"):
        var(f"omp-{token}", r)
lines += ["}", ""]
pathlib.Path(__file__).with_name("dr-pepper.css").write_text("\n".join(lines))
